import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {ComponentLibraryStore} from '../../packages/core/src/component-library-store.ts';
const root=resolve(import.meta.dirname,'../..'),output=join(import.meta.dirname,'profile-merge');
const report=JSON.parse(await readFile(join(output,'preflight.json'),'utf8'));
const staged=join(output,'combined-component-library.json'),legacy=JSON.parse(await readFile(staged,'utf8'));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const store=new ComponentLibraryStore(join(root,'library'));
assert.deepEqual(await store.list(),report.before,'canonical library changed since preflight');
for(const source of report.sources)assert.equal(hash(await readFile(source.path)),source.sha256,'profile changed since snapshot');
await new ComponentLibraryStore(join(root,'library'),{legacyPath:staged}).list();
for(const component of legacy.components)assert.deepEqual(await store.read(component.id),component);
report.after=await store.list();
for(const source of report.sources)assert.equal(hash(await readFile(source.path)),source.sha256,'original profile changed');
const portableStore=new ComponentLibraryStore(join(output,'standalone-seed'),{seedRoots:[join(root,'library')]});
assert.deepEqual(await portableStore.list(),report.after);
for(const component of legacy.components)assert.deepEqual(await portableStore.read(component.id),component);
report.applied=true;report.originalsUnchanged=true;report.standaloneSeedVerified=true;
await writeFile(join(output,'result.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({imported:legacy.components.length,total:report.after.length,originalsUnchanged:true,standaloneSeedVerified:true,names:report.after.map(row=>row.name)},null,2));
