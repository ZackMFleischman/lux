import assert from 'node:assert/strict';
import {readFile,writeFile,mkdtemp} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
const record=JSON.parse(await readFile(process.argv[2],'utf8'));
const {resolveStandardLibrary}=await import(pathToFileURL(join(record.workspace,'apps/studio/src/standard-library.ts')).href);
const appData=await mkdtemp(join(tmpdir(),'lux-packaged-location-'));
const common={workspace:record.workspace,appData,desktop:true};
const canonical=resolveStandardLibrary({...common,canonicalRoot:record.canonicalLibraryRoot});
assert.equal(canonical.kind,'repository');assert.equal(canonical.root,record.canonicalLibraryRoot);
const fallback=resolveStandardLibrary({...common,canonicalRoot:join(appData,'absent-repository','library')});
assert.equal(fallback.kind,'fallback');assert.equal(fallback.root,join(appData,'Lux','Studio','library'));
assert.deepEqual(fallback.seedRoots,[join(record.workspace,'library')]);
const catalog=JSON.parse(await readFile(join(record.workspace,'library/catalog.json'),'utf8'));
assert.ok(catalog.components.length>0);
const output={ok:true,sourceCommit:record.sourceCommit,node:process.execPath,workspace:record.workspace,canonical,fallback,packagedCatalog:catalog};
await writeFile(join(import.meta.dirname,'packaged-library-location.json'),JSON.stringify(output,null,2));
console.log(JSON.stringify(output,null,2));
