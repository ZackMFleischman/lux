import assert from 'node:assert/strict';
import { _electron } from 'playwright';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const root = resolve(import.meta.dirname, '..'), folder = join(root, 'artifacts/studio-parameters');
await mkdir(folder, { recursive: true });
const env = { ...process.env, LUX_NODE_EXECUTABLE: process.execPath, LUX_STUDIO_MCP_TEST: '1' };
delete env.ELECTRON_RUN_AS_NODE; delete env.LUX_STUDIO_SMOKE;
let app, client;
const report = { ok: false, checks: [], errors: [] };
try {
  app = await _electron.launch({ executablePath: createRequire(import.meta.url)('electron'), args: [join(root, 'apps/studio/dist/main.cjs')], cwd: root, env, timeout: 30000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000);
  page.on('pageerror', error => report.errors.push(error.stack ?? error.message));
  await page.getByRole('button', { name: 'Build', exact: true }).waitFor();
  const ownedPid = await app.evaluate(() => process.pid);
  let endpoint;
  for (let attempt = 0; attempt < 80; attempt++) {
    try { endpoint = JSON.parse(await readFile(join(process.env.APPDATA, 'Lux/Studio/agent-endpoint.json'), 'utf8')); if (endpoint.pid === ownedPid) break; } catch {}
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.equal(endpoint?.pid, ownedPid, 'Only control this test app');
  client = new Client({ name: 'lux-parameter-qa', version: '1.0.0' });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [join(root, 'scripts/studio-mcp.mjs')], cwd: root }));
  const raw = (name, args = {}) => client.callTool({ name: `lux.studio.${name}`, arguments: args }, undefined, { timeout: 75000 });
  const parse = result => JSON.parse(result.content.find(part => part.type === 'text').text);
  const call = async (name, args) => { const result = await raw(name, args); assert.equal(result.isError, undefined, JSON.stringify(result)); return parse(result); };
  const capture = async name => { const result = await raw('capture'); assert.equal(result.isError, undefined, JSON.stringify(result)); const bytes = result.content.find(part => part.type === 'image').data; await writeFile(join(folder, `${name}.png`), Buffer.from(bytes, 'base64')); return { bytes, metadata: parse(result) }; };
  const discovery = await call('discover');
  assert.equal(discovery.runningStudio.compatible, true);
  assert.equal(discovery.sdkVersion, '0.2.0');
  const initial = await call('read');
  const source = { sdkVersion: '0.2.0', entry: 'visual.ts', files: { 'visual.ts': await readFile(join(root, 'skills/lux-visual-creation/assets/noise-sphere.ts'), 'utf8') } };
  const built = await call('build', { expectedDraftVersion: initial.draftVersion, source });
  let runtime = built.status.authoring;
  assert.equal(runtime.sdkVersion, '0.2.0'); assert.equal(runtime.controlSchema.length, 5); assert.equal(runtime.intensity, undefined);
  await page.getByText('View', { exact: true }).click();
  await page.getByRole('button', { name: 'Reset desktop layout', exact: true }).click();
  await page.getByText('View', { exact: true }).click();
  assert.equal(await page.getByRole('slider').count(), 5);
  assert.equal(await page.getByRole('slider', { name: 'Intensity' }).count(), 0);
  const rows = await page.locator('.parameter-row').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().height));
  assert.ok(rows.every(height => height <= 54), 'Each parameter fits a compact row');
  report.controlHeights = rows;
  report.checks.push('Five code-defined sphere controls, no invented Intensity, matching running-app discovery');
  const playbackTarget = { instanceId: runtime.instanceId, expectedGeneration: runtime.generation };
  await call('playback', { ...playbackTarget, action: 'play' });
  for (let attempt = 0; attempt < 40; attempt++) {
    report.performance = (await call('status')).performance;
    if (report.performance?.status === 'live' && report.performance.worker?.cpuCall.sampleCount >= 10) break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.equal(report.performance?.status, 'live');
  assert.ok(report.performance.worker.cpuCall.sampleCount >= 10);
  assert.equal(report.performance.worker.cpuCall.gate, 'not_evaluated');
  assert.equal(report.performance.worker.gpu.gate, 'not_evaluated');
  await page.locator('summary').filter({ hasText: /^Performance$/ }).click();
  await page.getByLabel('Live performance').waitFor();
  report.performanceText = await page.getByLabel('Live performance').innerText();
  await page.locator('summary').filter({ hasText: /^Performance$/ }).click();
  await call('playback', { ...playbackTarget, action: 'pause' });
  report.checks.push('Real running CPU/GPU capability telemetry reaches agent status and the collapsed monitor without claiming budget acceptance');
  const target = () => ({ instanceId: runtime.instanceId, expectedGeneration: runtime.generation, expectedRevisionId: runtime.revisionId, expectedControlSchemaHash: runtime.controlSchemaHash });
  const zero = await call('parameters', { ...target(), values: { spikeHeight: 0, noiseScale: 2 } });
  assert.equal(zero.status.authoring.controls.roughness, 0.38);
  const smooth = await capture('smooth');
  const height = page.getByRole('spinbutton', { name: 'Spike height value', exact: true });
  await height.fill('1.8'); await height.press('Enter');
  await page.locator('[data-control-id="spikeHeight"][data-applied-value="1.8"]').waitFor();
  const spiky = await capture('spiky');
  assert.equal(spiky.metadata.controls.spikeHeight, 1.8); assert.notEqual(smooth.bytes, spiky.bytes);
  const noise = await call('parameters', { ...target(), values: { noiseScale: 8, sharpness: 2 } });
  const revised = await capture('revised');
  assert.notEqual(revised.bytes, spiky.bytes); assert.equal(revised.metadata.controls.spikeHeight, 1.8);
  assert.equal(noise.status.authoring.controls.roughness, 0.38);
  report.checks.push('Numeric UI and atomic MCP patches independently change visible shape and preserve untouched values');
  for (const args of [{ ...target(), values: { absent: 1 } }, { ...target(), expectedControlSchemaHash: 'f'.repeat(64), values: { spikeHeight: 1 } }, { ...target(), values: { roughness: 0.2, spikeHeight: 99 } }]) assert.equal((await raw('parameters', args)).isError, true);
  assert.equal((await call('status')).authoring.controls.roughness, 0.38);
  await page.getByRole('button', { name: 'Reset Spike height to default' }).click();
  await page.locator('[data-control-id="spikeHeight"][data-applied-value="0.85"]').waitFor();
  const savePath = join(folder, 'sphere.lux-scene');
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }); }, savePath);
  await page.locator('.file-tools > summary').click(); await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[aria-label="Unsaved changes"]'));
  const saved = JSON.parse(await readFile(savePath, 'utf8'));
  assert.equal(saved.version, 3); assert.equal(saved.controls.values.noiseScale, 8); assert.equal(saved.controls.values.spikeHeight, 0.85);
  await height.fill('1.1');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).waitFor();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  assert.equal(page.isClosed(), false, 'Unsubmitted numeric input must protect close');
  await page.locator('[data-control-id="spikeHeight"][data-applied-value="1.1"]').waitFor();
  await call('parameters', { ...target(), values: { spikeHeight: 0.2 } });
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, savePath);
  page.on('dialog', () => report.errors.push('Unexpected native JavaScript dialog'));
  await page.locator('.file-tools > summary').click(); await page.getByRole('button', { name: 'Open', exact: true }).click();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  assert.equal((await call('status')).authoring.controls.spikeHeight, 0.2);
  await page.locator('.file-tools > summary').click(); await page.getByRole('button', { name: 'Open', exact: true }).click();
  await page.getByRole('button', { name: 'Discard and open', exact: true }).click();
  await page.locator('[data-control-id="spikeHeight"][data-applied-value="0.85"]').waitFor();
  runtime = (await call('status')).authoring;
  assert.equal(runtime.controls.noiseScale, 8);
  const reopened = await capture('reopened'); assert.deepEqual(reopened.metadata.controls, saved.controls.values);
  const restarted = await call('restart', { instanceId: runtime.instanceId, expectedGeneration: runtime.generation });
  runtime = restarted.status.authoring; assert.deepEqual(runtime.controls, saved.controls.values);
  report.checks.push('Invalid/stale patches have no partial effect; default reset, scene-v3 save/open, and cached restart preserve all controls');
  await page.screenshot({ path: join(folder, 'studio.png') });
  const latest = await call('read');
  const bad = structuredClone(source); bad.files['visual.ts'] += '\nthis is invalid Typescript !!';
  assert.equal((await raw('build', { expectedDraftVersion: latest.draftVersion, source: bad })).isError, true);
  assert.deepEqual((await call('status')).authoring.controls, runtime.controls);
  let text = discovery.example.replace(/controls: \{[\s\S]*?\n  \},/, 'controls: {},').replaceAll('frame.controls.brightness', '0.5').replaceAll('frame.controls.speed', '0.35');
  const empty = await call('build', { expectedDraftVersion: latest.draftVersion, source: { sdkVersion: '0.2.0', entry: 'visual.ts', files: { 'visual.ts': text } } });
  assert.equal(empty.status.authoring.controlSchema.length, 0);
  await page.getByText('This visual defines no live controls.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('slider').count(), 0);
  const legacy = await call('build', { expectedDraftVersion: empty.draftVersion, source: initial.source });
  assert.equal(legacy.status.authoring.sdkVersion, '0.1.0');
  assert.equal(await page.getByRole('slider', { name: 'Intensity', exact: true }).count(), 1);
  report.checks.push('Failed code retains accepted values; empty schema works; legacy source remains compatible');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).waitFor();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  assert.equal(page.isClosed(), false);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  await Promise.all([page.waitForEvent('close'), page.getByRole('button', { name: 'Discard and close' }).click()]);
  report.checks.push('In-app Open/Close confirmations cancel safely and discard explicitly without native modal dialogs');
  assert.deepEqual(report.errors, []);
  report.ok = true;
} catch (error) { report.error = String(error.stack ?? error); console.error(error); process.exitCode = 1; }
finally { await client?.close(); if (app) { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); } await writeFile(join(folder, 'result.json'), JSON.stringify(report, null, 2)); }
console.log(JSON.stringify(report));
